/**
 * Internal component options grouped by checkout, display, callbacks, and
 * wallet configuration. These types are not package registration exports.
 */

import type { CartItem } from './core';

/**
 * Structural type matching @solana/wallet-adapter-base WalletAdapter.
 * Using a local interface avoids a runtime import of @solana/wallet-adapter-base
 * which Metro may resolve even for type-only imports.
 */
export interface WalletAdapterLike {
  name: string;
  connected: boolean;
  publicKey: { toBase58(): string } | null;
  connect(): Promise<void>;
  disconnect(): Promise<void>;
}

/**
 * Internal callback/event payment method surfaced to consumer callbacks
 * (onPaymentAttempt / onPaymentSuccess / onPaymentError). Uses `'crypto'` for the
 * Solana flow.
 *
 * Server payment-method wire values use `'x402'` for the same rail. Map between
 * the two at the callback/wire boundary.
 */
export type PaymentMethod = 'stripe' | 'crypto' | 'credits';

/**
 * Additional method identifiers; this type does not enable payment rails
 */
export type FuturePaymentMethod = PaymentMethod | 'ach' | 'sepa' | 'bank-transfer';

/**
 * Payment success callback payload
 */
export interface PaymentSuccessResult {
  transactionId: string;
  method: PaymentMethod;
  timestamp?: number;
}

/**
 * Callback payment-error payload passed to `onPaymentError`. The event-bus
 * `PaymentErrorDetail` in `utils/eventEmitter` also carries event metadata.
 */
export interface PaymentErrorDetail {
  message: string;
  code?: string;
  method?: PaymentMethod;
}

/**
 * Checkout-related options
 * Customer info, coupons, redirects, and attempt identity
 */
export interface CheckoutOptions {
  /** Caller-owned key; preserved byte-for-byte and never generated by the component. */
  idempotencyKey?: string;

  /** Caller-owned opaque lifecycle attempt identifier. */
  attemptId?: string;

  /** Customer email for receipts and Stripe checkout */
  customerEmail?: string;

  /** Coupon code for discounts (works with both Stripe and x402) */
  couponCode?: string;

  /** Stripe redirect URL on successful payment */
  successUrl?: string;

  /** Stripe redirect URL on cancelled payment */
  cancelUrl?: string;

  /** Metadata for tracking (e.g., userId, sessionId, orderId) */
  metadata?: Record<string, string>;

  /** JWT token from cedros-login for credits payment authentication */
  authToken?: string;
}

/**
 * Display/UI-related options
 * Labels, visibility, and layout
 */
export interface DisplayOptions {
  /** Label for card payment button */
  cardLabel?: string;

  /** Label for crypto payment button */
  cryptoLabel?: string;

  /** Label for unified purchase button */
  purchaseLabel?: string;

  /** Show card payment option */
  showCard?: boolean;

  /** Show crypto payment option */
  showCrypto?: boolean;

  /** Label for credits payment button */
  creditsLabel?: string;

  /** Show credits payment option (requires credits to be enabled on backend) */
  showCredits?: boolean;

  /** Show unified purchase button instead of separate buttons */
  showPurchaseButton?: boolean;

  /** Layout direction for dual payment buttons */
  layout?: 'vertical' | 'horizontal';

  /** Hide inline success/error messages */
  hideMessages?: boolean;

  /** Custom CSS class name */
  className?: string;

  /**
   * Custom modal renderer for purchase button
   * Note: Uses simplified callback signatures (string-based) for internal consistency with PurchaseButton
   */
  renderModal?: (props: {
    isOpen: boolean;
    onClose: () => void;
    resource?: string;
    items?: CartItem[];
    cardLabel?: string;
    cryptoLabel?: string;
    creditsLabel?: string;
    showCard?: boolean;
    showCrypto?: boolean;
    showCredits?: boolean;
    onPaymentAttempt?: (method: PaymentMethod) => void;
    onPaymentSuccess?: (txId: string) => void;
    onPaymentError?: (error: string) => void;
    customerEmail?: string;
    successUrl?: string;
    cancelUrl?: string;
    metadata?: Record<string, string>;
    couponCode?: string;
    testPageUrl?: string;
    hideMessages?: boolean;
  }) => React.ReactNode;
}

/**
 * Props passed to custom modal renderer
 */
export interface ModalRenderProps {
  isOpen: boolean;
  onClose: () => void;
  resource?: string;
  items?: CartItem[];
  cardLabel?: string;
  cryptoLabel?: string;
  creditsLabel?: string;
  showCard?: boolean;
  showCrypto?: boolean;
  showCredits?: boolean;
  onPaymentAttempt?: (method: PaymentMethod) => void;
  onPaymentSuccess?: (result: PaymentSuccessResult) => void;
  onPaymentError?: (error: PaymentErrorDetail) => void;
  customerEmail?: string;
  successUrl?: string;
  cancelUrl?: string;
  metadata?: Record<string, string>;
  couponCode?: string;
  testPageUrl?: string;
  hideMessages?: boolean;
}

/**
 * Callback/event handler options
 * Payment lifecycle events
 */
export interface CallbackOptions {
  /** Called when user initiates payment (for analytics) */
  onPaymentAttempt?: (method: PaymentMethod) => void;

  /** Called on successful payment */
  onPaymentSuccess?: (result: PaymentSuccessResult) => void;

  /** Called on payment error */
  onPaymentError?: (error: PaymentErrorDetail) => void;
}

/**
 * Advanced/power-user options
 * Wallet configuration and testing
 */
export interface AdvancedOptions {
  /** Custom wallet adapters (overrides default pool) */
  wallets?: WalletAdapterLike[];

  /** URL to open for crypto testing (for example, a local test page) */
  testPageUrl?: string;
}
