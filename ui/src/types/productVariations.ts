export type ProductImage = {
  url: string;
  alt?: string;
};

/** A value within a variation type, such as "Medium" for Size. */
export type VariationValue = {
  id: string;
  label: string;
  parentValueId?: string;
};

/** Product variation dimension, such as Size or Color. */
export type VariationType = {
  id: string;
  name: string;
  displayOrder: number;
  values: VariationValue[];
};

/** Product-level variation configuration used by admin SKU tooling. */
export type ProductVariationConfig = {
  variationTypes: VariationType[];
};

/** Admin-editable product variant/SKU data. */
export type ProductVariant = {
  id: string;
  title: string;
  optionValueIds: string[];
  price?: number;
  compareAtPrice?: number;
  inventoryStatus?: 'in_stock' | 'low' | 'out_of_stock' | 'backorder';
  inventoryQuantity?: number;
  sku?: string;
  images?: ProductImage[];
  autoGenerated?: boolean;
};
