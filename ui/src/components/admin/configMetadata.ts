/** Check if a field is a secret for a given category */
export function isSecretField(category: string, field: string): boolean {
  const cat = CONFIG_CATEGORIES[category];
  return cat?.secrets.includes(field) ?? false;
}

/** Field metadata with type/label/secret resolved from config value + category. */
export interface ResolvedFieldMeta extends Omit<FieldMeta, 'type'> {
  type: NonNullable<FieldMeta['type']> | 'string' | 'object';
  isSecret: boolean;
  label: string;
}

/** Resolve display metadata for a config field, inferring type from the value when unset. */
export function resolveFieldMeta(
  category: string,
  key: string,
  value: unknown
): ResolvedFieldMeta {
  const fieldMeta = CONFIG_CATEGORIES[category]?.fields?.[key] ?? {};
  const isSecret = isSecretField(category, key);
  const label =
    fieldMeta.label ?? key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

  let type: ResolvedFieldMeta['type'] | undefined = fieldMeta.type;
  if (!type) {
    if (typeof value === 'boolean') type = 'boolean';
    else if (typeof value === 'number') type = 'number';
    else if (Array.isArray(value)) type = 'array';
    else if (typeof value === 'object' && value !== null) type = 'object';
    else type = 'string';
  }

  return { ...fieldMeta, type, isSecret, label };
}

/** Placeholder for redacted secrets */
export const REDACTED_VALUE = '[REDACTED]';

/**
 * Client-side cross-field hints (warnings, not errors).
 * Currently flags Stripe keys whose test/live prefix contradicts the selected mode.
 */
export function getClientFieldWarnings(
  category: string,
  values: Record<string, unknown>
): Record<string, string> {
  if (category !== 'stripe') return {};
  const warnings: Record<string, string> = {};
  const mode = values['mode'];
  if (mode !== 'test' && mode !== 'live') return warnings;

  for (const key of ['publishable_key', 'secret_key']) {
    const value = values[key];
    if (typeof value !== 'string' || value === REDACTED_VALUE) continue;
    const isTestKey = value.startsWith('pk_test_') || value.startsWith('sk_test_');
    const isLiveKey = value.startsWith('pk_live_') || value.startsWith('sk_live_');
    if (mode === 'live' && isTestKey) {
      warnings[key] = 'This is a test key, but live mode is selected.';
    } else if (mode === 'test' && isLiveKey) {
      warnings[key] = 'This is a live key, but test mode is selected.';
    }
  }
  return warnings;
}
