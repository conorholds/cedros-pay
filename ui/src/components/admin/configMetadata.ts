/**
 * Config category metadata for the Pay hub settings UI.
 *
 * Declares which config fields are shown, in what order and grouping,
 * and with what user-facing copy. Field declaration order here is the
 * display order. Fields not listed render after listed ones; fields the
 * server doesn't return are simply skipped.
 */

/** Field metadata for special input types */
export interface FieldMeta {
  type?:
    | 'dropdown'
    | 'segmented'
    | 'number'
    | 'boolean'
    | 'array'
    | 'textarea'
    | 'token_mint'
    | 'toggle'
    | 'solana_address';
  /** User-facing label. Falls back to a prettified key name. */
  label?: string;
  placeholder?: string;
  /**
   * Value used when the server returns this key empty (''/null/undefined), so a
   * fresh config lands on a sensible selection instead of a blank control. Filled
   * into both the saved baseline and the draft, so it shows selected without
   * reading as an unsaved change.
   */
  default?: string | number | boolean;
  options?: string[];
  /** Display labels for dropdown/segmented options, keyed by value. */
  optionLabels?: Record<string, string>;
  unit?: string;
  description?: string;
  /** "Where do I find this?" link rendered under the field. */
  helpUrl?: string;
  helpLabel?: string;
  hidden?: boolean;
  /** Render inside the collapsed "Advanced" section. */
  advanced?: boolean;
  /** Only show when another (boolean) config key is truthy. */
  showWhen?: string;
  /** Render inside the named field group (see CategoryMeta.groups). */
  group?: string;
}

/** A titled group of fields with an optional master toggle (e.g. Apple / Google). */
export interface FieldGroupMeta {
  id: string;
  title: string;
  description?: string;
  /** Boolean config key rendered as a switch in the group header; fields hide when off. */
  toggleField?: string;
}

/** A server endpoint the user must paste into an external dashboard. */
export interface EndpointMeta {
  label: string;
  /** Appended to the configured server URL. */
  path: string;
  description?: string;
  group?: string;
}

/** Category metadata */
export interface CategoryMeta {
  label: string;
  description?: string;
  secrets: string[];
  icon: string;
  fields?: Record<string, FieldMeta>;
  groups?: FieldGroupMeta[];
  endpoints?: EndpointMeta[];
}

